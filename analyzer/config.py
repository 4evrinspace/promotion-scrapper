def assign_group(name: str) -> str:
    """Определяет товарную группу по ключевым словам названия."""
    text = str(name).lower().replace("`", " ")
    for group, _category, keywords in GROUP_KEYWORDS:
        if any(keyword in text for keyword in keywords):
            return group
    return "не распознано"


GROUP_CATEGORY = {group: category for group, category, _ in GROUP_KEYWORDS}


def assign_category(shop: str, group: str | None = None) -> str:
    """Категория по товарной группе; если группа не распознана — по магазину."""
    if group and group in GROUP_CATEGORY:
        return GROUP_CATEGORY[group]
    return SHOP_CATEGORY.get(shop, "прочее")


class FakePromoConfig:
    """Пороги и веса детектора «лже-акций».

    Правила делятся на структурные (событие с ценой внутри акции — это и есть
    признак манипуляции) и справочные (косвенные, в скор не входят, но выводятся
    в отчёт как контекст). Скор нормируется на сумму весов структурных правил,
    поэтому всегда лежит в [0, 1].
    """

    def __init__(
        self,
        old_price_jump_pct: float = 5.0,       # рост «старой» цены при неизменной промо
        promo_rise_pct: float = 2.0,           # рост промо-цены внутри активной акции
        both_rise_pct: float = 5.0,            # синхронный рост обеих цен
        both_rise_discount_tol: float = 1.5,   # допуск по глубине скидки, п.п.
        depth_swing_pp: float = 10.0,          # размах глубины скидки внутри акции, п.п.
        worse_than_best_pct: float = 3.0,      # насколько текущая цена хуже лучшей
        outlier_quantile: float = 0.95,        # справочно: скидка — выброс в своей группе
        w_old_jump: float = 1.0,
        w_promo_rise: float = 0.8,
        w_both_rise: float = 1.0,
        w_depth_swing: float = 0.5,
        w_worse_than_best: float = 0.6,
        suspicious: float = 0.30,
        likely_fake: float = 0.60,
    ):
        self.old_price_jump_pct = old_price_jump_pct
        self.promo_rise_pct = promo_rise_pct
        self.both_rise_pct = both_rise_pct
        self.both_rise_discount_tol = both_rise_discount_tol
        self.depth_swing_pp = depth_swing_pp
        self.worse_than_best_pct = worse_than_best_pct
        self.outlier_quantile = outlier_quantile
        self.w_old_jump = w_old_jump
        self.w_promo_rise = w_promo_rise
        self.w_both_rise = w_both_rise
        self.w_depth_swing = w_depth_swing
        self.w_worse_than_best = w_worse_than_best
        self.suspicious = suspicious
        self.likely_fake = likely_fake

    @property
    def total_weight(self) -> float:
        return (
            self.w_old_jump
            + self.w_promo_rise
            + self.w_both_rise
            + self.w_depth_swing
            + self.w_worse_than_best
        )
